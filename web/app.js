  function createAudioLayer() {
    let ctx = null; let master = null; let timer = null; let whiteBuf = null;
    const nodes = [];
    let intensity = 0.55;

    function brownNoise(seconds) {
      const len = Math.floor(ctx.sampleRate * seconds);
      const buf = ctx.createBuffer(1, len, ctx.sampleRate);
      const d = buf.getChannelData(0);
      let last = 0;
      for (let i = 0; i < len; i++) {
        const w = Math.random() * 2 - 1;
        last = (last + 0.02 * w) / 1.02;
        d[i] = last * 3.5;
      }
      return buf;
    }
    function whiteNoise(seconds) {
      const len = Math.floor(ctx.sampleRate * seconds);
      const buf = ctx.createBuffer(1, len, ctx.sampleRate);
      const d = buf.getChannelData(0);
      for (let i = 0; i < len; i++) d[i] = Math.random() * 2 - 1;
      return buf;
    }

    function whisper() {
      if (!ctx || !master) return;
      const now = ctx.currentTime;
      const src = ctx.createBufferSource(); src.buffer = whiteBuf;
      const bp = ctx.createBiquadFilter(); bp.type = 'bandpass';
      bp.frequency.setValueAtTime(900 + Math.random() * 1800, now);
      bp.frequency.linearRampToValueAtTime(600 + Math.random() * 2600, now + 0.4);
      bp.Q.value = 6 + Math.random() * 10;
      const env = ctx.createGain();
      const dur = 0.25 + Math.random() * 0.6;
      env.gain.setValueAtTime(0.0001, now);
      env.gain.exponentialRampToValueAtTime(0.35 + intensity * 0.4, now + 0.06);
      env.gain.exponentialRampToValueAtTime(0.0001, now + dur);
      let tail = env;
      if (ctx.createStereoPanner) {
        const pan = ctx.createStereoPanner(); pan.pan.value = Math.random() * 2 - 1;
        env.connect(pan); tail = pan;
      }
      src.connect(bp).connect(env); tail.connect(master);
      src.start(now); src.stop(now + dur + 0.1);
    }

    function schedule() {
      const gap = 700 + Math.random() * 3200 * (1.3 - intensity);
      timer = setTimeout(() => { whisper(); if (Math.random() < intensity * 0.6) setTimeout(whisper, 120); schedule(); }, gap);
    }

    function start() {
      const AC = window.AudioContext || window.webkitAudioContext;
      if (!AC) return false;
      if (!ctx) ctx = new AC();
      if (ctx.state === 'suspended') ctx.resume();
      whiteBuf = whiteBuf || whiteNoise(1.2);
      master = ctx.createGain(); master.gain.setValueAtTime(0.0001, ctx.currentTime);
      master.gain.exponentialRampToValueAtTime(0.6, ctx.currentTime + 1.5);
      master.connect(ctx.destination);

      // Low detuned drone.
      const droneGain = ctx.createGain(); droneGain.gain.value = 0.09; droneGain.connect(master);
      [55, 57.4, 110.6].forEach((f) => {
        const o = ctx.createOscillator(); o.type = 'sawtooth'; o.frequency.value = f;
        const lp = ctx.createBiquadFilter(); lp.type = 'lowpass'; lp.frequency.value = 240;
        o.connect(lp).connect(droneGain); o.start(); nodes.push(o);
      });
      // Breathing filtered noise bed.
      const bed = ctx.createBufferSource(); bed.buffer = brownNoise(4); bed.loop = true;
      const bp = ctx.createBiquadFilter(); bp.type = 'bandpass'; bp.frequency.value = 600; bp.Q.value = 1.3;
      const bedGain = ctx.createGain(); bedGain.gain.value = 0.3;
      bed.connect(bp).connect(bedGain).connect(master); bed.start(); nodes.push(bed);
      const lfo = ctx.createOscillator(); lfo.frequency.value = 0.17;
      const lfoGain = ctx.createGain(); lfoGain.gain.value = 420;
      lfo.connect(lfoGain).connect(bp.frequency); lfo.start(); nodes.push(lfo);
      schedule();
      return true;
    }

    function stop() {
      clearTimeout(timer); timer = null;
      if (!ctx || !master) return;
      const m = master; const stopping = nodes.splice(0);
      m.gain.cancelScheduledValues(ctx.currentTime);
      m.gain.setValueAtTime(m.gain.value, ctx.currentTime);
      m.gain.exponentialRampToValueAtTime(0.0001, ctx.currentTime + 0.8);
      setTimeout(() => { stopping.forEach((n) => { try { n.stop(); } catch (e) { /* already stopped */ } }); m.disconnect(); }, 900);
      master = null;
    }

    return { start, stop, setIntensity(v) { intensity = v; }, get active() { return master !== null; } };
  }

  /* Wire the simulation slide. */
  function initSimulation() {
    const host = document.getElementById('simStage');
    const overlay = document.getElementById('simOverlay');
    const startBtn = document.getElementById('simStart');
    const intensity = document.getElementById('intensity');
    const intensityOut = document.getElementById('intensityOut');
    const drift = document.getElementById('drift');
    const wire = document.getElementById('wireframe');
    const audioToggle = document.getElementById('audio');
    const resetBtn = document.getElementById('simReset');
    const pauseBtn = document.getElementById('simPause');
    const audio = createAudioLayer();
    let scene = null;
    let userPaused = false;

    if (reducedMotion) { intensity.value = 25; intensityOut.value = 25; drift.checked = false; }

    function ensureScene() {
      if (scene) return scene;
      scene = window.THREE ? createWebGLScene(host) : create2DScene(host);
      scene.setIntensity(intensity.value / 100);
      scene.setDrift(drift.checked);
      scene.setWireframe(wire.checked);
      return scene;
    }

    startBtn.addEventListener('click', () => {
      overlay.hidden = true;
      userPaused = false;
      ensureScene().start();
      pauseBtn.textContent = 'השהיה';
    });
    intensity.addEventListener('input', () => {
      intensityOut.value = intensity.value;
      const v = intensity.value / 100;
      if (scene) scene.setIntensity(v);
      audio.setIntensity(v);
    });
    drift.addEventListener('change', () => scene && scene.setDrift(drift.checked));
    wire.addEventListener('change', () => scene && scene.setWireframe(wire.checked));
    audioToggle.addEventListener('change', () => {
      if (audioToggle.checked) {
        audio.setIntensity(intensity.value / 100);
        if (!audio.start()) audioToggle.checked = false;
      } else {
        audio.stop();
      }
    });
    resetBtn.addEventListener('click', () => {
      intensity.value = reducedMotion ? 25 : 55; intensityOut.value = intensity.value;
      drift.checked = !reducedMotion; wire.checked = false;
      if (scene) { scene.setIntensity(intensity.value / 100); scene.setDrift(drift.checked); scene.setWireframe(false); scene.reset(); }
      audio.setIntensity(intensity.value / 100);
    });
    pauseBtn.addEventListener('click', () => {
      if (!scene) return;
      if (scene.isRunning()) { scene.stop(); userPaused = true; pauseBtn.textContent = 'המשך'; }
      else { scene.start(); userPaused = false; pauseBtn.textContent = 'השהיה'; }
    });

    document.addEventListener('visibilitychange', () => {
      if (!scene) return;
      if (document.hidden) scene.stop();
      else if (current === SIM_SLIDE - 1 && !userPaused && overlay.hidden) scene.start();
    });

    return {
      resume() { if (scene && !userPaused && overlay.hidden) scene.start(); },
      suspend() {
        if (scene) scene.stop();
        if (audio.active) { audio.stop(); audioToggle.checked = false; }
      },
    };
  }

