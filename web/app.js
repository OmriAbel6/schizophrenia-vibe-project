  function createWebGLScene(host) {
    const THREE = window.THREE;
    const renderer = new THREE.WebGLRenderer({ antialias: true });
    renderer.setPixelRatio(Math.min(window.devicePixelRatio || 1, 2));
    host.appendChild(renderer.domElement);

    const scene = new THREE.Scene();
    scene.background = new THREE.Color(0x0b1120);
    scene.fog = new THREE.FogExp2(0x0b1120, 0.075);

    const camera = new THREE.PerspectiveCamera(60, 1, 0.1, 100);
    camera.position.set(0, 0, 6.5);

    scene.add(new THREE.AmbientLight(0x334155, 0.9));
    const lightA = new THREE.PointLight(0x38bdf8, 1.4, 30);
    const lightB = new THREE.PointLight(0x818cf8, 1.2, 30);
    const lightC = new THREE.PointLight(0xf472b6, 0.6, 20);
    scene.add(lightA, lightB, lightC);

    // Central morphing body.
    const geo = new THREE.IcosahedronGeometry(1.7, 5);
    const basePos = Float32Array.from(geo.attributes.position.array);
    const mat = new THREE.MeshStandardMaterial({
      color: 0x38bdf8, emissive: 0x1e1b4b, roughness: 0.3, metalness: 0.45,
    });
    const blob = new THREE.Mesh(geo, mat);
    scene.add(blob);

    // Translucent wire shell that breathes around the body.
    const shell = new THREE.Mesh(
      new THREE.IcosahedronGeometry(2.7, 1),
      new THREE.MeshBasicMaterial({ color: 0x818cf8, wireframe: true, transparent: true, opacity: 0.16 }),
    );
    scene.add(shell);

    // Floating, un-anchored geometries.
    const shapeFns = [
      () => new THREE.TetrahedronGeometry(0.3),
      () => new THREE.OctahedronGeometry(0.28),
      () => new THREE.TorusKnotGeometry(0.17, 0.05, 48, 8),
      () => new THREE.BoxGeometry(0.3, 0.3, 0.3),
      () => new THREE.TorusGeometry(0.22, 0.06, 10, 24),
    ];
    const palette = [0x38bdf8, 0x818cf8, 0xf472b6, 0x94a3b8];
    const floaters = [];
    for (let i = 0; i < 30; i++) {
      const m = new THREE.Mesh(
        shapeFns[i % shapeFns.length](),
        new THREE.MeshStandardMaterial({
          color: palette[i % palette.length], wireframe: i % 3 === 0,
          roughness: 0.5, metalness: 0.3, emissive: 0x0f172a,
        }),
      );
      scene.add(m);
      floaters.push({
        mesh: m, seed: Math.random() * Math.PI * 2, radius: 3 + Math.random() * 3.5,
        speed: 0.08 + Math.random() * 0.22, tilt: Math.random() * 1.2 - 0.6,
      });
    }

    // Drifting particle field.
    const count = 1800;
    const pArr = new Float32Array(count * 3);
    for (let i = 0; i < pArr.length; i++) pArr[i] = (Math.random() - 0.5) * 20;
    const pGeo = new THREE.BufferGeometry();
    pGeo.setAttribute('position', new THREE.BufferAttribute(pArr, 3));
    const particles = new THREE.Points(pGeo, new THREE.PointsMaterial({
      color: 0x94a3b8, size: 0.045, transparent: true, opacity: 0.55,
    }));
    scene.add(particles);

    const state = { intensity: 0.55, drift: true, running: false, t: 0 };
    let last = performance.now();

    function resize() {
      const w = host.clientWidth || 1; const h = host.clientHeight || 1;
      renderer.setSize(w, h, false);
      camera.aspect = w / h;
      camera.updateProjectionMatrix();
    }
    new ResizeObserver(resize).observe(host);
    resize();

    function update() {
      const t = state.t; const a = state.intensity;
      const pos = geo.attributes.position;
      const amp = 0.14 + a * 0.7; const freq = 0.85 + a * 1.2;
      for (let i = 0; i < pos.count; i++) {
        const ix = i * 3;
        const x = basePos[ix]; const y = basePos[ix + 1]; const z = basePos[ix + 2];
        const n1 = noise3(x * freq + t * 0.6, y * freq + t * 0.45, z * freq + t * 0.35);
        const n2 = noise3(x * freq * 2.4 - t * 0.9, y * freq * 2.4 + t * 0.3, z * freq * 2.4);
        const d = 1 + amp * (n1 * 0.75 + n2 * 0.25);
        pos.setXYZ(i, x * d, y * d, z * d);
      }
      pos.needsUpdate = true;
      geo.computeVertexNormals();
      blob.rotation.y = t * 0.15;
      blob.rotation.x = Math.sin(t * 0.2) * 0.3;
      mat.color.setHSL((0.56 + Math.sin(t * 0.23) * (0.05 + a * 0.12) + 1) % 1, 0.8, 0.55);
      mat.emissive.setHSL((0.7 + Math.sin(t * 0.11) * 0.1 + 1) % 1, 0.6, 0.12 + a * 0.08);

      shell.rotation.set(t * 0.07, -t * 0.11, t * 0.03);
      shell.scale.setScalar(1 + Math.sin(t * 0.6) * 0.1 * a);

      floaters.forEach((f) => {
        const ang = f.seed + t * f.speed;
        const r = f.radius + Math.sin(t * 0.8 + f.seed) * 0.8 * a;
        f.mesh.position.set(Math.cos(ang) * r, Math.sin(ang * 0.7 + f.seed) * r * 0.55 + f.tilt, Math.sin(ang) * r);
        f.mesh.rotation.x += 0.008 + a * 0.02;
        f.mesh.rotation.y += 0.011;
        f.mesh.scale.setScalar(1 + Math.sin(t * 2 + f.seed) * 0.45 * a);
      });

      particles.rotation.y = t * 0.02;
      particles.rotation.x = Math.sin(t * 0.1) * 0.12;

      lightA.position.set(Math.sin(t * 0.5) * 5, 3, Math.cos(t * 0.5) * 5);
      lightB.position.set(Math.cos(t * 0.33) * -5, -2 + Math.sin(t) * a, Math.sin(t * 0.33) * 4);
      lightC.position.set(0, Math.sin(t * 0.7) * 4, 3);
      lightA.intensity = 1.2 + Math.sin(t * 1.7) * 0.6 * a;

      // Camera drift and perceptual (perspective) distortion.
      const d = state.drift ? a : 0;
      camera.position.set(Math.sin(t * 0.31) * 1.3 * d, Math.cos(t * 0.21) * 0.9 * d, 6.5 + Math.sin(t * 0.17) * 1.6 * d);
      camera.lookAt(Math.sin(t * 0.9) * 0.4 * d, Math.cos(t * 0.7) * 0.3 * d, 0);
      camera.rotation.z += Math.sin(t * 0.27) * 0.3 * d;
      camera.fov = 60 + Math.sin(t * 0.45) * 30 * d + Math.sin(t * 1.9) * 6 * d;
      camera.updateProjectionMatrix();
    }

    function frame(now) {
      if (!state.running) return;
      const dt = Math.min((now - last) / 1000, 0.05);
      last = now;
      state.t += dt * (0.5 + state.intensity * 1.0);
      update();
      renderer.render(scene, camera);
      requestAnimationFrame(frame);
    }

    return {
      kind: 'webgl',
      start() { if (state.running) return; state.running = true; last = performance.now(); resize(); requestAnimationFrame(frame); },
      stop() { state.running = false; },
      isRunning() { return state.running; },
      setIntensity(v) { state.intensity = v; },
      setDrift(b) { state.drift = b; if (!b) { camera.rotation.z = 0; camera.fov = 60; camera.position.set(0, 0, 6.5); camera.lookAt(0, 0, 0); camera.updateProjectionMatrix(); } },
      setWireframe(b) { mat.wireframe = b; },
      reset() { state.t = 0; },
    };
  }

  /* Fallback: 2D canvas particle field when Three.js is unavailable. */
  function create2DScene(host) {
    const canvas = document.createElement('canvas');
    host.appendChild(canvas);
    const ctx = canvas.getContext('2d');
    const state = { intensity: 0.55, drift: true, running: false, t: 0 };
    const dots = Array.from({ length: 220 }, () => ({
      x: Math.random(), y: Math.random(), r: 2 + Math.random() * 6, s: Math.random() * Math.PI * 2,
    }));
    function resize() { canvas.width = host.clientWidth; canvas.height = host.clientHeight; }
    new ResizeObserver(resize).observe(host); resize();
    function frame() {
      if (!state.running) return;
      state.t += 0.016 * (0.5 + state.intensity);
      const { width: w, height: h } = canvas; const a = state.intensity; const t = state.t;
      ctx.fillStyle = 'rgba(11,17,32,0.35)'; ctx.fillRect(0, 0, w, h);
      dots.forEach((p) => {
        const x = (p.x + Math.sin(t * 0.3 + p.s) * 0.08 * a) * w;
        const y = (p.y + Math.cos(t * 0.25 + p.s) * 0.08 * a) * h;
        const r = p.r * (1 + Math.sin(t * 2 + p.s) * 0.6 * a);
        ctx.beginPath(); ctx.arc(x, y, Math.max(0.5, r), 0, Math.PI * 2);
        ctx.fillStyle = `hsla(${200 + Math.sin(t + p.s) * 40 * a}, 80%, 65%, 0.7)`; ctx.fill();
      });
      requestAnimationFrame(frame);
    }
    return {
      kind: '2d',
      start() { if (state.running) return; state.running = true; requestAnimationFrame(frame); },
      stop() { state.running = false; },
      isRunning() { return state.running; },
      setIntensity(v) { state.intensity = v; },
      setDrift(b) { state.drift = b; },
      setWireframe() {},
      reset() { state.t = 0; },
    };
  }

