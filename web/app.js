  const SVG_NS = 'http://www.w3.org/2000/svg';
  const tooltip = document.getElementById('tooltip');

  function svgEl(name, attrs = {}, text) {
    const el = document.createElementNS(SVG_NS, name);
    Object.entries(attrs).forEach(([k, v]) => el.setAttribute(k, v));
    if (text !== undefined) el.textContent = text;
    return el;
  }

  function showTooltip(html, x, y) {
    tooltip.innerHTML = html;
    tooltip.hidden = false;
    const r = tooltip.getBoundingClientRect();
    const left = Math.min(window.innerWidth - r.width - 8, Math.max(8, x - r.width / 2));
    const top = y - r.height - 14 < 8 ? y + 18 : y - r.height - 14;
    tooltip.style.left = `${left}px`;
    tooltip.style.top = `${top}px`;
  }
  const hideTooltip = () => { tooltip.hidden = true; };

  function niceMax(v, step) { return Math.ceil(v / step) * step; }

  function legend(host, items) {
    host.innerHTML = '';
    items.forEach((it) => {
      const span = document.createElement('span');
      span.className = 'legend__item';
      const sw = document.createElement('span');
      sw.className = `legend__swatch ${it.kind ? `legend__swatch--${it.kind}` : ''}`;
      if (it.color) sw.style.background = it.color;
      span.append(sw, document.createTextNode(it.label));
      host.appendChild(span);
    });
  }

  function renderTable(host, headers, rows) {
    const table = document.createElement('table');
    const thead = document.createElement('thead'); const tr = document.createElement('tr');
    headers.forEach((h) => { const th = document.createElement('th'); th.textContent = h; tr.appendChild(th); });
    thead.appendChild(tr); table.appendChild(thead);
    const tbody = document.createElement('tbody');
    rows.forEach((row) => {
      const r = document.createElement('tr');
      row.forEach((c) => { const td = document.createElement('td'); td.textContent = c; r.appendChild(td); });
      tbody.appendChild(r);
    });
    table.appendChild(tbody);
    host.innerHTML = ''; host.appendChild(table);
  }

  /* Grouped columns: domains on x, scenarios as series. */
  function renderDomainChart(metrics, phase) {
    const host = document.getElementById('domainChart');
    const domains = ['positive', 'negative', 'general'];
    const labels = metrics.meta.scale.domain_labels_he;
    const scenarios = metrics.scenarios;
    const W = 720; const H = 340; const m = { top: 20, right: 16, bottom: 44, left: 44 };
    const pw = W - m.left - m.right; const ph = H - m.top - m.bottom;
    const yMax = niceMax(Math.max(...scenarios.map((s) => s[phase].general)), 20);
    const y = (v) => m.top + ph - (v / yMax) * ph;

    const svg = svgEl('svg', { viewBox: `0 0 ${W} ${H}`, role: 'img', 'aria-label': 'ציוני PANSS לפי ממד ותרחיש' });
    const grid = svgEl('g', { class: 'grid' });
    for (let v = 0; v <= yMax; v += 20) {
      grid.appendChild(svgEl('line', { x1: m.left, x2: W - m.right, y1: y(v), y2: y(v) }));
      svg.appendChild(svgEl('text', { class: 'tick', x: m.left - 8, y: y(v) + 4, 'text-anchor': 'end' }, v));
    }
    svg.appendChild(grid);
    svg.appendChild(svgEl('line', { class: 'axis', x1: m.left, x2: W - m.right, y1: y(0), y2: y(0), stroke: '#3b4a63' }));

    const groupW = pw / domains.length;
    const barW = Math.min(24, (groupW - 40) / scenarios.length - 2);
    const bars = [];
    domains.forEach((dom, di) => {
      // Right-to-left group order so Hebrew readers meet "positive" first.
      const gx = m.left + (domains.length - 1 - di) * groupW;
      const total = scenarios.length * barW + (scenarios.length - 1) * 2;
      const start = gx + (groupW - total) / 2;
      svg.appendChild(svgEl('text', { class: 'label', x: gx + groupW / 2, y: H - 14, 'text-anchor': 'middle' }, labels[dom]));
      scenarios.forEach((s, si) => {
        const v = s[phase][dom];
        const x = start + (scenarios.length - 1 - si) * (barW + 2);
        const top = y(v); const bottom = y(0); const r = 4;
        const d = `M${x},${bottom} V${top + r} a${r},${r} 0 0 1 ${r},-${r} h${barW - 2 * r} a${r},${r} 0 0 1 ${r},${r} V${bottom} Z`;
        const path = svgEl('path', { d, fill: SERIES[si], class: 'bar' });
        path.addEventListener('mouseenter', (e) => {
          bars.forEach((b) => b.classList.toggle('is-dim', b !== path));
          showTooltip(`<div class="tooltip__title">${labels[dom]} · ${phase === 'baseline' ? 'בסיס' : 'סיום'}</div>
            <div class="tooltip__row"><span class="legend__swatch" style="background:${SERIES[si]}"></span>${s.name_he}<b>${v}</b></div>`, e.clientX, e.clientY);
        });
        path.addEventListener('mousemove', (e) => showTooltip(tooltip.innerHTML, e.clientX, e.clientY));
        path.addEventListener('mouseleave', () => { bars.forEach((b) => b.classList.remove('is-dim')); hideTooltip(); });
        bars.push(path);
        svg.appendChild(path);
        // Direct-label only the tallest bar of each group; the tooltip and table carry the rest.
        if (v === Math.max(...scenarios.map((sc) => sc[phase][dom]))) {
          svg.appendChild(svgEl('text', { class: 'end-label', x: x + barW / 2, y: top - 6, 'text-anchor': 'middle' }, v));
        }
      });
    });
    host.innerHTML = ''; host.appendChild(svg);

    legend(document.getElementById('domainLegend'), scenarios.map((s, i) => ({ color: SERIES[i], label: s.name_he })));
    renderTable(document.getElementById('domainTable'),
      ['תרחיש', labels.positive, labels.negative, labels.general, 'סה״כ'],
      scenarios.map((s) => [s.name_he, s[phase].positive, s[phase].negative, s[phase].general, s[phase].total]));
  }

  /* Multi-series line chart: PANSS total per week. */
  function renderTrajectoryChart(metrics) {
    const host = document.getElementById('trajectoryChart');
    const scenarios = metrics.scenarios;
    const weeks = metrics.meta.weeks;
    const W = 760; const H = 330; const m = { top: 18, right: 54, bottom: 36, left: 44 };
    const pw = W - m.left - m.right; const ph = H - m.top - m.bottom;
    const allTotals = scenarios.flatMap((s) => s.trajectory.map((p) => p.total));
    const yMin = Math.floor(Math.min(...allTotals) / 20) * 20;
    const yMax = niceMax(Math.max(...allTotals), 20);
    const x = (w) => m.left + (w / weeks) * pw;
    const y = (v) => m.top + ph - ((v - yMin) / (yMax - yMin)) * ph;

    const svg = svgEl('svg', { viewBox: `0 0 ${W} ${H}`, role: 'img', 'aria-label': 'מסלול ציון PANSS כולל לפי שבוע' });
    const grid = svgEl('g', { class: 'grid' });
    for (let v = yMin; v <= yMax; v += 20) {
      grid.appendChild(svgEl('line', { x1: m.left, x2: W - m.right, y1: y(v), y2: y(v) }));
      svg.appendChild(svgEl('text', { class: 'tick', x: m.left - 8, y: y(v) + 4, 'text-anchor': 'end' }, v));
    }
    svg.appendChild(grid);
    for (let w = 0; w <= weeks; w += weeks >= 40 ? 8 : 4) {
      svg.appendChild(svgEl('text', { class: 'tick', x: x(w), y: H - 16, 'text-anchor': 'middle' }, w));
    }
    svg.appendChild(svgEl('text', { class: 'label', x: W - m.right, y: H - 2, 'text-anchor': 'end' }, 'שבוע'));

    scenarios.forEach((s, si) => {
      const pts = s.trajectory.map((p) => `${x(p.week).toFixed(1)},${y(p.total).toFixed(1)}`);
      svg.appendChild(svgEl('path', { class: 'series-line', d: `M${pts.join(' L')}`, stroke: SERIES[si] }));
      s.relapses.forEach((r) => {
        const p = s.trajectory[Math.min(r.week + Math.floor(r.duration_weeks / 2), weeks)];
        svg.appendChild(svgEl('circle', { class: 'relapse', cx: x(p.week), cy: y(p.total), r: 6 }));
      });
      const end = s.trajectory[s.trajectory.length - 1];
      svg.appendChild(svgEl('circle', { class: 'ring', cx: x(end.week), cy: y(end.total), r: 4.5, fill: SERIES[si] }));
      svg.appendChild(svgEl('text', { class: 'end-label', x: x(end.week) + 9, y: y(end.total) + 4 }, end.total));
    });

    // Hover layer: crosshair + per-series dots + tooltip.
    const cross = svgEl('line', { class: 'crosshair', y1: m.top, y2: m.top + ph, visibility: 'hidden' });
    const dots = scenarios.map((s, i) => svgEl('circle', { class: 'ring hover-dot', r: 4.5, fill: SERIES[i], visibility: 'hidden' }));
    svg.append(cross, ...dots);
    const hit = svgEl('rect', { x: m.left, y: m.top, width: pw, height: ph, fill: 'transparent' });
    hit.addEventListener('mousemove', (e) => {
      const rect = svg.getBoundingClientRect();
      const px = ((e.clientX - rect.left) / rect.width) * W;
      const w = Math.max(0, Math.min(weeks, Math.round(((px - m.left) / pw) * weeks)));
      cross.setAttribute('x1', x(w)); cross.setAttribute('x2', x(w)); cross.setAttribute('visibility', 'visible');
      const rows = scenarios.map((s, i) => {
        const p = s.trajectory[w];
        dots[i].setAttribute('cx', x(w)); dots[i].setAttribute('cy', y(p.total)); dots[i].setAttribute('visibility', 'visible');
        return `<div class="tooltip__row"><span class="legend__swatch" style="background:${SERIES[i]}"></span>${s.name_he}<b>${p.total}</b></div>`;
      });
      showTooltip(`<div class="tooltip__title">שבוע ${w}</div>${rows.join('')}`, e.clientX, e.clientY);
    });
    hit.addEventListener('mouseleave', () => {
      cross.setAttribute('visibility', 'hidden'); dots.forEach((d) => d.setAttribute('visibility', 'hidden')); hideTooltip();
    });
    svg.appendChild(hit);
    host.innerHTML = ''; host.appendChild(svg);

    legend(document.getElementById('trajectoryLegend'), [
      ...scenarios.map((s, i) => ({ color: SERIES[i], label: s.name_he, kind: 'line' })),
      { kind: 'ring', label: 'אירוע הישנות (שיא)' },
    ]);
    const step = weeks >= 40 ? 4 : 2;
    const sample = scenarios[0].trajectory.filter((p) => p.week % step === 0 || p.week === weeks);
    renderTable(document.getElementById('trajectoryTable'),
      ['שבוע', ...scenarios.map((s) => s.name_he)],
      sample.map((p) => [p.week, ...scenarios.map((s) => s.trajectory[p.week].total)]));

    const tiles = document.getElementById('reductionTiles');
    tiles.innerHTML = '';
    scenarios.forEach((s, i) => {
      const red = s.assessment.response.percent_reduction;
      const tile = document.createElement('div');
      tile.className = 'stat';
      tile.style.borderInlineStart = `4px solid ${SERIES[i]}`;
      tile.innerHTML = `<span class="stat__label">${s.name_he}</span>
        <span class="stat__value"><bdi>${red.toFixed(1)}%</bdi></span>
        <span class="stat__delta ${red >= 20 ? 'stat__delta--good' : 'stat__delta--bad'}">${red >= 20 ? '▼' : '•'} הפחתה מהבסיס המתוקן (${s.baseline.total} → ${s.endpoint.total})</span>`;
      tiles.appendChild(tile);
    });
  }

  function renderAssessments(metrics) {
    const host = document.getElementById('assessmentCards');
    host.innerHTML = '';
    metrics.scenarios.forEach((s, i) => {
      const a = s.assessment;
      const card = document.createElement('article');
      card.className = 'card assessment';
      card.dataset.series = String(i + 1);
      const sevClass = { minimal: 'good', mild: 'good', moderate: 'warn', marked: 'warn', severe: 'crit' }[a.severity.key] || '';
      const respClass = a.response.responder_50 ? 'good' : a.response.responder_20 ? 'warn' : 'crit';
      const remClass = a.remission.sustained_remission ? 'good' : a.remission.symptomatic_at_endpoint ? 'warn' : 'crit';
      card.innerHTML = `
        <h3>${s.name_he}</h3>
        <div class="stat">
          <span class="stat__label">הפחתת PANSS מתוקנת</span>
          <span class="stat__value"><bdi>${a.response.percent_reduction.toFixed(1)}%</bdi></span>
          <span class="stat__note">${s.treatment.name_he}</span>
        </div>
        <div class="badges">
          <span class="badge badge--${sevClass}">חומרה: ${a.severity.label_he}</span>
          <span class="badge badge--${respClass}">${a.response.label_he}</span>
          <span class="badge badge--${remClass}">${a.remission.label_he}</span>
          <span class="badge">${a.dominant_dimension.label_he}</span>
          <span class="badge">הישנויות: <bdi>${a.relapse_count}</bdi></span>
        </div>
        <ul class="flags">${a.flags.map((f) => `<li>${f.label_he}</li>`).join('')}</ul>`;
      host.appendChild(card);
    });
  }

  async function loadMetrics() {
    try {
      const res = await fetch('metrics.json', { cache: 'no-store' });
      if (!res.ok) throw new Error(res.statusText);
      return { data: await res.json(), source: 'metrics.json (fetch)' };
    } catch (err) {
      if (window.SCHIZO_METRICS) return { data: window.SCHIZO_METRICS, source: 'metrics.js (מוטמע)' };
      return { data: null, source: null };
    }
  }

  function initCharts() {
    const meta = document.getElementById('metricsMeta');
    loadMetrics().then(({ data, source }) => {
      if (!data) {
        meta.textContent = 'לא נמצאו נתונים. הריצו python main.py בתיקיית python כדי ליצור metrics.json.';
        return;
      }
      const when = new Date(data.meta.generated_at);
      meta.innerHTML = `מקור: <bdi>${source}</bdi> · נוצר <bdi>${when.toLocaleString('he-IL')}</bdi> · <bdi>seed=${data.meta.seed}</bdi> · <bdi>${data.meta.weeks}</bdi> שבועות`;
      let phase = 'baseline';
      renderDomainChart(data, phase);
      renderTrajectoryChart(data);
      renderAssessments(data);
      document.querySelectorAll('[data-phase]').forEach((btn) => {
        btn.addEventListener('click', () => {
          phase = btn.dataset.phase;
          document.querySelectorAll('[data-phase]').forEach((b) => b.classList.toggle('is-active', b === btn));
          renderDomainChart(data, phase);
        });
      });
    });
    document.querySelectorAll('[data-table]').forEach((btn) => {
      btn.addEventListener('click', () => {
        const target = document.getElementById(btn.dataset.table);
        target.hidden = !target.hidden;
        btn.classList.toggle('is-active', !target.hidden);
      });
    });
  }

