QUESTION_IDS: Sequence[str] = tuple(str(q["id"]) for q in QUESTIONS)


def question_catalog() -> List[Dict[str, str]]:
    """The tile list without answers (what the UI needs to render tiles)."""
    return [
        {"id": str(q["id"]), "label_he": str(q["label_he"]), "icon": str(q["icon"])}
        for q in QUESTIONS
    ]


def answers_for(question_id: str, state: str) -> List[str]:
    for question in QUESTIONS:
        if question["id"] == question_id:
            answers = question["answers"]  # type: ignore[index]
            return list(answers[state])  # type: ignore[index]
    raise KeyError(question_id)


def as_document() -> Dict[str, object]:
    """Everything the browser fallback needs, in one JSON-serialisable dict."""
    return {
        "states": list(STATES),
        "state_labels_he": dict(STATE_LABELS_HE),
        "openers": dict(OPENERS),
        "questions": QUESTIONS,
    }


def export_js(path: pathlib.Path) -> None:
    payload = json.dumps(as_document(), ensure_ascii=False, indent=2)
    path.write_text(
        "// Generated by python/dialogue.py – do not edit by hand.\n"
        f"window.PATIENT_DIALOGUE = {payload};\n",
        encoding="utf-8",
    )


def main(argv: List[str]) -> int:
    parser = argparse.ArgumentParser(description="Dialogue bank utilities.")
    parser.add_argument(
        "--export",
        type=pathlib.Path,
        default=pathlib.Path(__file__).resolve().parent.parent / "web" / "dialogue.js",
        help="write the bank as a browser global (default: ../web/dialogue.js)",
    )
    args = parser.parse_args(argv)
    export_js(args.export)
    total = sum(
        len(q["answers"][s]) for q in QUESTIONS for s in STATES  # type: ignore[index]
    )
    print(f"wrote {args.export} ({len(QUESTIONS)} tiles, {total} answers)")
    return 0


